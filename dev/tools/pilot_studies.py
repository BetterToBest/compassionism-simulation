def load(s):
    d = os.path.join(SRC, 'pilot-%s-%s' % (s, ENG))
    fs = sorted(f for f in glob.glob(os.path.join(d, 'shard-*.json')) if not f.endswith('.timing.json'))
    parts = [json.load(open(f)) for f in fs]
    parts.sort(key=lambda p: p['_meta']['seeds'][0])
    seeds = []
    for p in parts:
        lo, hi = p['_meta']['seeds']
        assert not seeds or lo == seeds[-1] + 1, (s, lo)
        seeds += list(range(lo, hi + 1))
    rows = {}
    for r in parts[0]['rows']:
        rows[r] = {k: np.array(sum((p['rows'][r][k] for p in parts), []), dtype=float) for k in parts[0]['rows'][r]}
    assert seeds == list(range(1, 51)), s
    return rows, d


rng = np.random.default_rng(BSEED)
def resample():
    idx = rng.integers(0, 50, size=(NB, 50))
    W = np.zeros((NB, 50))
    np.add.at(W, (np.repeat(np.arange(NB), 50), idx.ravel()), 1.0 / 50)
    return W

