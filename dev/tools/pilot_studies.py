def est(x, Wm):
    b = Wm @ x
    return float(x.mean()), float(np.percentile(b, 2.5)), float(np.percentile(b, 97.5)), b


def eff(row, none, key, kind):
    if kind == 'red':
        return none[key] - row[key]
    if kind == 'infl':
        return (row[key] - none[key]) * 100
    return row[key] - none[key]


def lvl(row, key, kind):
    return (row[key] - 1) * 100 if kind == 'infl' else row[key]


def f(x, d=1):
    if abs(x) >= 1000:
        return '{:,.0f}'.format(x)
    return ('{:.%df}' % d).format(x)


def fi(e, d=1):
    return '%s [%s, %s]' % (f(e[0], d), f(e[1], d), f(e[2], d))


def excl0(e):
    return e[1] > 0 or e[2] < 0


