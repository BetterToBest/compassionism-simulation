def cell(mask):
    return ''.join(ch if mask & (1 << i) else ch.lower() for i, ch in enumerate(PARTS))


def vfun(rows, p, k, kind, raise_):
    """per-seed v(S) for every subset mask 0..31 (v(empty) = 0)."""
    N = rows[p + 'none']; v = {0: np.zeros(50)}
    for m in range(1, 32):
        nm = 'main' if m == 31 else cell(m)
        rn = p + nm + ('.raise' if raise_ and m & 1 else '')
        v[m] = eff(rows[rn], N, k, kind)
    return v


def shapley(v):
    phi = []
    for i in range(5):
        tot = np.zeros(50)
        for m in range(32):
            if m & (1 << i):
                continue
            s = bin(m).count('1')
            tot = tot + math.factorial(s) * math.factorial(4 - s) / math.factorial(5) * (v[m | (1 << i)] - v[m])
        phi.append(tot)
    return phi


def contrasts(v):
    c = {'whole design': v[31] - sum(v[1 << i] for i in range(5))}
    for i, j in combinations(range(5), 2):
        bi, bj = 1 << i, 1 << j
        c['%s x %s' % (PNAME[PARTS[i]], PNAME[PARTS[j]])] = v[31] - v[31 ^ bi] - v[31 ^ bj] + v[31 ^ bi ^ bj]
    return c


def holm(ps):
    order = sorted(range(len(ps)), key=lambda i: ps[i]); ok = [False] * len(ps); m = len(ps)
    for r, i in enumerate(order):
        if ps[i] <= 0.05 / (m - r):
            ok[i] = True
        else:
            break
    return ok


def bootp(b):
    """two-sided bootstrap p-value: twice the smaller tail share beyond zero."""
    return min(1.0, 2 * min((b <= 0).mean(), (b >= 0).mean()))


SYN = {}
def synergy_block(s, rows, Wm, p, y, raise_, title, full=True):
    out('### %s' % title)
    out('')
    outs = [(lab, k, kind) for lab, k, kind in PRI[y] if k != 'bOAPy' or full]
    out('Shapley values (points; $ for cost) and, where v(all five) excludes zero, shares of the full effect in %:')
    out('')
    out('| Outcome | v(all five) | ' + ' | '.join(PNAME[c] for c in PARTS) + ' |')
    out('|---|---|' + '---|' * 5)
    for lab, k, kind in outs:
        v = vfun(rows, p, k, kind, raise_)
        vt = est(v[31], Wm)
        phi = shapley(v)
        cells = []
        for i, ph in enumerate(phi):
            e = est(ph, Wm); rec(s, p + ('raise' if raise_ else 'off'), k, 'shapley ' + PNAME[PARTS[i]], e)
            sh = ''
            if excl0(vt):
                # share replicate by replicate: phi_b / v_b
                sb = e[3] / vt[3] * 100
                se = (e[0] / vt[0] * 100, np.percentile(sb, 2.5), np.percentile(sb, 97.5))
                rec(s, p + ('raise' if raise_ else 'off'), k, 'shapley share % ' + PNAME[PARTS[i]], se)
                sh = '; %s%%' % f(se[0], 0)
            cells.append(fi(e, 2 if kind != 'diff' else 0) + sh)
        out('| %s | %s | %s |' % (SHORT[k], fi(vt, 2 if kind != 'diff' else 0), ' | '.join(cells)))
    out('')
    out('Interaction contrasts (points; $ for cost); positive = the parts together do more than their separate effects'
        ' add up to. † = interval excludes zero; M = also material (1 point, 5% of the full cost); H = survives Holm over the 11 contrasts.')
    out('')
    names = list(contrasts({m: np.zeros(1) for m in range(32)}).keys())
    out('| Outcome | ' + ' | '.join(names) + ' |')
    out('|---|' + '---|' * len(names))
    for lab, k, kind in outs:
        v = vfun(rows, p, k, kind, raise_)
        vt = v[31].mean()
        cs = contrasts(v); es = {n: est(cs[n], Wm) for n in names}
        hp = holm([bootp(es[n][3]) for n in names])
        cells = []
        for n, h in zip(names, hp):
            e = es[n]; rec(s, p + ('raise' if raise_ else 'off'), k, 'contrast ' + n, e)
            thr = 0.05 * abs(vt) if kind == 'diff' else 1.0
            fl = ('†' if excl0(e) else '') + ('M' if excl0(e) and abs(e[0]) >= thr else '') + ('H' if h else '')
            SYN.setdefault((s, p, raise_, k), {})[n] = (e[0], e[1], e[2], excl0(e), excl0(e) and abs(e[0]) >= thr, h)
            cells.append(fi(e, 2 if kind != 'diff' else 0) + (' ' + fl if fl else ''))
        out('| %s | %s |' % (SHORT[k], ' | '.join(cells)))
    out('')


