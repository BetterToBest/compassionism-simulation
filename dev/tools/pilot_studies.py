        cells, fav = [], True
        for n, k in PO:
            x = eff(R, N, k, 'red'); ee = est(x, Wm); dp = est(x - q / 90 * e90[k], Wm)
            rec(s, p + 'p%d%s' % (q, '.raise' if raise_ else ''), k, 'effect', ee); rec(s, p + 'p%d%s' % (q, '.raise' if raise_ else ''), k, 'departure', dp)
