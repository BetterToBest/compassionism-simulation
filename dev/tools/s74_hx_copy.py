#!/usr/bin/env python3
"""S74: the engine's copy of the history paths (index.html `var HX = ...`), built from sources/s74_history.json
and sources/history/macro_drivers.csv (real median household income). Usage:
  python3 dev/tools/s74_hx_copy.py          print the line
  python3 dev/tools/s74_hx_copy.py check    fail if index.html's line differs from the sources
"""
import csv, json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
KEYS = [('cpi', 'cpi'), ('hR', 'homeCSReal'), ('eR', 'eqReal'), ('ff', 'ff'), ('sh', 'shadow'), ('m30', 'm30'), ('y10', 'y10'),
        ('ug', 'ugap'), ('yg', 'ygap'), ('rm', 'recMonths'), ('un', 'unemp'), ('fa', 'fedAssetsGDP'), ('fm', 'fedMBSGDP'),
        ('food', 'food'), ('shel', 'shelter'), ('med', 'medical'), ('t1', 'dfaTop1'), ('b50', 'dfaBottom50')]
def line():
    d = json.load(open(os.path.join(ROOT, 'sources', 's74_history.json')))
    yrs = d['years']; s = d['series']
    mhi = {}
    for r in csv.DictReader(open(os.path.join(ROOT, 'sources', 'history', 'macro_drivers.csv'))):
        if r['series'] == 'real_median_household_income': mhi[int(r['year'])] = float(r['value'])
    parts = ['y0:%d' % yrs[0], 'n:%d' % len(yrs)]
    for k, src in KEYS: parts.append('%s:[%s]' % (k, ','.join(repr(float(v)) if not float(v).is_integer() else str(int(v)) for v in s[src])))
    parts.append('mhi:[%s]' % ','.join(str(int(mhi[y])) for y in yrs))
    return 'var HX = {' + ', '.join(parts) + '};  /* S74: generated by dev/tools/s74_hx_copy.py from sources/s74_history.json (do not edit by hand) */'
if __name__ == '__main__':
    L = line()
    if len(sys.argv) > 1 and sys.argv[1] == 'check':
        src = open(os.path.join(ROOT, 'index.html'), encoding='utf-8').read().split('\n')
        got = [x for x in src if x.startswith('var HX = {')]
        if got != [L]: print('index.html HX differs from the sources'); sys.exit(1)
        print('HX matches the sources')
    else: print(L)
