#!/usr/bin/env node
// Writes dev/CODEMAP.md: a short map of the big files, so a session can jump to
// the right line range instead of reading or blind-searching them.
// Run from the repository root:  node dev/tools/codemap.js
// It only reads files and writes dev/CODEMAP.md. Line numbers go stale after any
// edit to the mapped files; regenerate before ending a session that changed them.
'use strict';
const fs = require('fs');
const cp = require('child_process');

const read = f => fs.readFileSync(f, 'utf8').split('\n');
const cut = (s, n) => (s.length > n ? s.slice(0, n - 1) + '…' : s);
const out = [];
const w = s => out.push(s);

let commit = 'unknown';
try { commit = cp.execSync('git rev-parse --short HEAD', { encoding: 'utf8' }).trim(); } catch (e) {}

w('# Code map');
w('');
w('Generated by node dev/tools/codemap.js at commit ' + commit + '. Line numbers move after any edit to a mapped file: confirm with grep, and regenerate before ending a session that changed them.');
w('');
w('**Do not read this file whole** (about 15,000 tokens). Grep it, for example grep -n "PRICE_RULE" dev/CODEMAP.md, then open only that range with sed -n A,Bp or Read offset/limit. Lines in index.html and harness.js are very long: print narrow ranges.');
w('');

// ---- code files ------------------------------------------------------------
function codeFile(file, first, last) {
  const L = read(file);
  const lo = first || 1, hi = last || L.length;
  w('## ' + file + ' (' + L.length + ' lines; map covers ' + lo + '-' + hi + ')');
  w('');
  const marks = [];
  const items = []; // every top-level function / var / const / let: [line, kind, name]
  for (let i = lo - 1; i < hi; i++) {
    const s = L[i];
    let m;
    if ((m = /^\/\*\s*====\s*(.*?)\s*====/.exec(s))) marks.push([i + 1, m[1]]);
    else if ((m = /^function\s+([A-Za-z_$][\w$]*)/.exec(s))) items.push([i + 1, 'fn', m[1]]);
    else if ((m = /^(?:var|const|let)\s+([A-Za-z_$][\w$]*)/.exec(s))) items.push([i + 1, 'var', m[1]]);
  }
  if (marks.length) {
    w('Regions:');
    marks.forEach(m => w('- ' + m[0] + ': ' + cut(m[1], 120)));
    w('');
  }
  w('One line per top-level item: `file:first-last kind name` (last = line before the next top-level item). Switches and constants are the uppercase vars.');
  w('');
  items.forEach((it, k) => {
    const end = k + 1 < items.length ? items[k + 1][0] - 1 : hi;
    const upper = it[1] === 'var' && /^[A-Z][A-Z0-9_]{2,}$/.test(it[2]);
    if (it[1] === 'fn' || upper) w(file + ':' + it[0] + '-' + end + ' ' + (it[1] === 'fn' ? 'fn' : 'const') + ' ' + it[2]);
  });
  w('');
}

// index.html: map only the main script block
(function () {
  const L = read('index.html');
  let a = 0, b = 0;
  for (let i = 0; i < L.length; i++) {
    if (!a && /^<script>\s*$/.test(L[i])) a = i + 2;
    else if (a && !b && /^<\/script>\s*$/.test(L[i])) { b = i; break; }
  }
  codeFile('index.html', a || 1, b || L.length);
})();
codeFile('harness.js');

// ---- document tables of contents -------------------------------------------
function toc(file, depth) {
  const L = read(file);
  w('## ' + file + ' (' + L.length + ' lines)');
  w('');
  L.forEach((s, i) => {
    const m = /^(#{1,6})\s+(.*)/.exec(s);
    if (m && m[1].length <= depth) w('- ' + (i + 1) + ': ' + cut(m[2], 130));
  });
  w('');
}
['dev/DECISIONS.md', 'dev/PROGRESS.md', 'HANDOFF.md'].forEach(f => fs.existsSync(f) && toc(f, 2));
if (fs.existsSync('MODEL_SPEC.md')) toc('MODEL_SPEC.md', 3);

// ---- tools and reports -----------------------------------------------------
function firstNote(file) {
  const L = read(file).slice(0, 12);
  for (const s of L) {
    let m;
    if (/^#!/.test(s) || /^\s*['"]use strict['"]/.test(s)) continue;
    if ((m = /^\s*(?:\/\/|#)\s*(.{8,})/.exec(s))) return m[1];
    if ((m = /^\s*(?:\/\*+|"""|''')\s*(.{8,})/.exec(s))) return m[1].replace(/\*\/\s*$/, '');
  }
  return '';
}
w('## dev/tools (first comment line of each)');
w('');
fs.readdirSync('dev/tools').sort().forEach(f => {
  const p = 'dev/tools/' + f;
  if (fs.statSync(p).isFile() && /\.(js|py|sh)$/.test(f)) w('- ' + f + (firstNote(p) ? ': ' + cut(firstNote(p), 110) : ''));
});
w('');
w('## dev/reports (title of each)');
w('');
fs.readdirSync('dev/reports').sort().forEach(f => {
  const p = 'dev/reports/' + f;
  if (fs.statSync(p).isFile() && /\.md$/.test(f)) {
    const t = read(p).find(s => /^#\s/.test(s));
    w('- ' + f + (t ? ': ' + cut(t.replace(/^#\s+/, ''), 110) : ''));
  }
});
w('');

fs.writeFileSync('dev/CODEMAP.md', out.join('\n'));
console.log('dev/CODEMAP.md written: ' + out.length + ' lines');
