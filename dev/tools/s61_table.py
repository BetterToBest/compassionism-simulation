"""S61 (Nov 9, 2026; research-update prereg/2026-11-s61-baseline-scope.md): tables of the baseline-scope pilot against S34's outside figures.
Reads dev/runs/s61-scope/s61-scope-ENV.json and -ENV-prog.json (dev/tools/s61_scope.js) and writes dev/runs/s61-scope/tables.md.
Outside figures: S34's table (dev/reports/baseline-realism.md, section 1) and, for adults outside the labour force, sources/lf_scope.json. The gap rules are
S34's: a share more than 3 points away, a dollar level outside 0.80-1.25 of the outside figure. Usage: python3 dev/tools/s61_table.py [DIR]"""
import json, os, sys
D = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', 'runs', 's61-scope')
LF = json.load(open(os.path.join(os.path.dirname(__file__), '..', '..', 'sources', 'lf_scope.json')))
US = [  # (label, path in a snapshot, outside figure, kind, source)
    ('Adults 25-64 with any earnings in the year', 'earnShare', 80.9, '%', 'CPS ASEC 2026'),
    ('Median earnings, adults with earnings', 'earnMed', 60000, '$', 'CPS ASEC 2026'),
    ('Official poverty, adults', 'fplAdult', 8.5, '%', 'CPS ASEC 2026, 25-64'),
    ('Official poverty, children', 'fplKid', 13.4, '%', 'CPS ASEC 2026, under 18'),
    ('Official poverty, adults and children', 'fplAll', 10.0, '%', 'CPS ASEC 2026'),
    ('Median household money income', 'hhIncMed', 105000, '$', 'CPS ASEC 2026, householder 25-64'),
    ('Median family net worth', 'wealth.all.median', 185600, '$', 'SCF 2025, head 25-64 with wages'),
    ('Families in debt (net worth below zero)', 'wealth.all.neg', 9.3, '%', 'SCF 2025'),
    ('Families with net worth below $25,000', 'wealth.all.below25k', 23.5, '%', 'SCF 2025'),
    ('In debt, single adults', 'wealth.sg.neg', 15.6, '%', 'SCF 2025'),
    ('In debt, single parents', 'wealth.sp.neg', 19.2, '%', 'SCF 2025'),
    ('In debt, couples without children', 'wealth.cn.neg', 5.9, '%', 'SCF 2025'),
    ('In debt, couples with children', 'wealth.ck.neg', 4.1, '%', 'SCF 2025'),
    ('Median net worth, single parents', 'wealth.sp.median', 49000, '$', 'SCF 2025'),
]
NAMES = {'F0': 'frozen yardstick', 'DC': 'cap ($2,500)', 'DF': 'floor + cap', 'DC0': 'cap $0 (S35)', 'DC5': 'cap $5,000', 'DC87': 'cap $8,700', 'DC10': 'cap $10,000',
         'DCL': 'cap, liquid share 0.046', 'L': 'lf', 'LC': 'lf + cap', 'LF': 'lf + floor', 'LCn': 'lf (no conversion) + cap', 'F0age': 'frozen, ageing', 'LCage': 'lf + cap, ageing'}
def get(o, p):
    for k in p.split('.'):
        o = o.get(k) if isinstance(o, dict) else None
        if o is None: return None
    return o.get('mean') if isinstance(o, dict) else o
def fmt(v, kind):
    if v is None: return '-'
    return ('%.1f%%' % v) if kind == '%' else ('$%s' % format(int(round(v, -2)), ','))
def gap(v, us, kind):
    if v is None: return ''
    return ' *' if (abs(v - us) > 3 if kind == '%' else not (0.8 <= v/us <= 1.25)) else ''
L = ['# S61 baseline-scope pilot: tables', '', 'Generated by `python3 dev/tools/s61_table.py` from `dev/runs/s61-scope/*.json` (`node dev/tools/s61_scope.js ENV 100 20 [--prog]`). '
     'Pilot: seeds 1-100, 500 adults, 20 years; means over seeds. Every row is the frozen yardstick (frozen engine, CPS earnings, today\'s safety net) plus the named reading. '
     '* marks a gap under S34\'s rules (a share more than 3 points from the outside figure; a dollar level outside 0.80-1.25 of it). Outside figures: S34\'s table.', '']
for env in ['ref', 'adv', 'st']:
    f = os.path.join(D, 's61-scope-%s.json' % env)
    if not os.path.exists(f): continue
    R = json.load(open(f)); rows = [r for r in NAMES if r in R['rows']]
    L += ['## %s: no-programme rows against the US' % {'ref': 'Reference', 'adv': 'Adverse', 'st': 'Stress'}[env], '',
          'Engine commit `%s` (dirty %s); %d seeds; command `%s`.' % (R['_meta']['manifest'].get('commit', '?')[:7], R['_meta']['manifest'].get('dirty'), R['_meta']['seeds'], R['_meta']['command']), '']
    for yk, yl in [('y0', 'Year 0'), ('end', 'Year 20')]:
        L += ['**%s**' % yl, '', '| Measure | US | ' + ' | '.join(NAMES[r] for r in rows) + ' |', '|---|---|' + '---|'*len(rows)]
        for lab, p, us, kind, src in US:
            L.append('| %s | %s | ' % (lab, fmt(us, kind)) + ' | '.join(fmt(get(R['rows'][r][yk], p), kind) + gap(get(R['rows'][r][yk], p), us, kind) for r in rows) + ' |')
        L.append('')
    L += ['**The engine\'s own measures (whole run)**', '', '| Measure | ' + ' | '.join(NAMES[r] for r in rows) + ' |', '|---|' + '---|'*len(rows)]
    for k, lab in [('fgt0PY', 'Adult-years below the cost of living (basket poverty), %'), ('pov', 'Adults with too little wealth at the end (wealth poverty), %'), ('hhCostPY', 'Household cost-of-living measure, %'),
                   ('hhDebt20', 'Families in debt at year 20 (engine key), %'), ('drHit', 'Graded spending decisions cut by the limit, %'), ('drCut', 'Mean cut when the limit binds, year-0 $'),
                   ('lfShare', 'Adults outside the labour force, %'), ('lfInc0', 'Their mean own income, year-0 $'), ('lfZero', 'Of them, with no own income, %')]:
        L.append('| %s | ' % lab + ' | '.join(('-' if R['rows'][r]['engine'].get(k) is None else ('%.0f' % R['rows'][r]['engine'][k] if k in ('drCut', 'lfInc0') else '%.2f' % R['rows'][r]['engine'][k])) for r in rows) + ' |')
    L.append('')
    lfr = [r for r in rows if r.startswith('L')]
    if lfr:
        L += ['**Adults outside the labour force, by reason (Year 0 / Year 20)**', '', '| Reason | CPS official poverty | ' + ' | '.join(NAMES[r] + ': poverty, median family net worth, in debt' for r in lfr) + ' |', '|---|---|' + '---|'*len(lfr)]
        for k, lab in [('dis', 'Disability'), ('ret', 'Early retirement'), ('care', 'Care of home or family'), ('sch', 'School'), ('inLF', 'In the labour force')]:
            cell = lambda r: ' / '.join('%s, %s, %s' % (fmt(get(R['rows'][r][y], 'lf.%s.fpl' % k), '%'), fmt(get(R['rows'][r][y], 'lf.%s.nwMed' % k), '$'), fmt(get(R['rows'][r][y], 'lf.%s.neg' % k), '%')) for y in ('y0', 'end'))
            L.append('| %s | %.1f%% | ' % (lab, LF['officialPoverty'][k]*100) + ' | '.join(cell(r) for r in lfr) + ' |')
        L.append('')
    fp = os.path.join(D, 's61-scope-%s-prog.json' % env)
    if os.path.exists(fp):
        G = json.load(open(fp))['prog']
        L += ['**The C2.2 design\'s effect under each reading (criterion C4; pilot, not a result)**', '', 'Paired difference, programme minus its own no-programme row, points, with the 2.5th-97.5th percentile of 2,000 paired bootstrap replicates over seeds.', '',
              '| Reading | Basket poverty | Wealth poverty | Cost-of-living measure |', '|---|---|---|---|']
        for r in [x for x in NAMES if x in G]:
            e = G[r]['effect']; c = lambda k: '%.2f [%.2f, %.2f]' % (e[k]['m'], e[k]['lo'], e[k]['hi']) if k in e else '-'
            L.append('| %s | %s | %s | %s |' % (NAMES[r], c('fgt0PY'), c('pov'), c('hhCostPY')))
        L.append('')
open(os.path.join(D, 'tables.md'), 'w').write('\n'.join(L) + '\n')
print('wrote', os.path.join(D, 'tables.md'))
